export const itemDescription = (name) =>
  itemDescriptions[name] || "セットに同梱される備品です。";
const catalog = new Map(products.map((p) => [p.id, p]));
export function summarizeContents(plan) {
  const result = new Map(
    groups.map(([key, label, unit, description]) => [
      key,
      { key, label, unit, description, count: 0, items: new Map() },
    ]),
  );
  const quantities = new Map();
  for (const id of plan.rows.flat())
    quantities.set(id, (quantities.get(id) || 0) + 1);
  for (const [id, quantity] of quantities) {
    let bags = 0,
      agents = 0,
      kits = 0;
    for (const [name, amount] of catalog.get(id).items) {
      const [key, factor = 1] = entries[name] || ["other"];
      const group = result.get(key);
      const n = amount * quantity;
      group.items.set(name, (group.items.get(name) || 0) + n);
      if (key !== "toilet") group.count += n * factor;
      else if (name === "非常用簡易トイレ") kits += n;
      else if (name.startsWith("汚物収納袋")) bags += n;
      else if (name.endsWith("凝固剤")) agents += n;
    }
    result.get("toilet").count += kits + Math.min(bags, agents);
  }
  return [...result.values()]
    .filter((g) => g.items.size)
    .map((g) => ({
      ...g,
      items: [...g.items].map(([name, count]) => ({
        name,
        count,
        unit: itemUnits[name] || "点",
        description: itemDescription(name),
      })),
    }));
}
